import {
    createIcons,
    Menu,
    ArrowRight,
    Globe,
    SquareArrowOutUpRight,
    PlayingCardsFan,
    Tags,
    Clock,
    Earth,
    UsersCollaboration,
    Brush,
    BookBookmark,
    MessageCircleQuestionMark,
    Sparkles,
} from 'js/lucide.min.js';
// import { updateOverlaySize } from './modules/overlay.js';
import { tintSVG } from './modules/svg.js';
import { ParseThisTimeInterval } from './modules/time.js';
import { initImagePreviews } from './modules/image-preview.js';

console.log('This site was generated by Hugo.');

let b = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
let debounce = false;

document.addEventListener('DOMContentLoaded', function (e) {
    const primary = {};
    const secondary = {};
    b.forEach(a => {
        primary[a] = getComputedStyle(document.documentElement).getPropertyValue(`--color-primary-${a}`).trim();
        secondary[a] = getComputedStyle(document.documentElement).getPropertyValue(`--color-secondary-${a}`).trim();
    });

    // globalThis.borderOverlay = document.querySelector('.border-overlay');
    // globalThis.container = document.getElementById('real-container');
    // updateOverlaySize();
    // globalThis.borderOverlay.style.display = 'fixed';

    const svgpromise = SVGInject(document.querySelectorAll('img.injectable'));

    svgpromise.then(() => {
        document.querySelectorAll("svg.tint").forEach(el => {
            let media = window.matchMedia("(prefers-color-scheme: dark)");
            thematicColorChange(media, primary); // Initial call to set the initial theme

            if (typeof media.addEventListener === 'function') {
                media.addEventListener('change', e => thematicColorChange(e, primary));
            } else if (typeof media.addListener === 'function') {
                media.addListener(thematicColorChange(function (e_) { thematicColorChange(e_, primary); }));
            }

        });
    });

    window.addEventListener('load', initImagePreviews);


    // const svgflood = document.getElementById("svgflood");
    // svgflood.setAttribute("flood-color", primary[500]);


    const re = /\s*:\/\//;
    document.querySelectorAll('a').forEach(elem => {
        const href = elem.getAttribute("href");
        if (href && href.match(re)) {
            const originalClasses = elem.getAttribute("class") ?? "";
            elem.setAttribute("class", `${originalClasses} ex`);
            elem.setAttribute("target", "_blank");
            const externalMarker = document.createElement('i');
            externalMarker.setAttribute('data-lucide', 'square-arrow-out-up-right');
            externalMarker.setAttribute('width', '16px');
            externalMarker.setAttribute('height', '16px');
            externalMarker.setAttribute('class', 'external-icon');
            externalMarker.style.display = 'inline-block';
            elem.appendChild(externalMarker);
        }
    });

    document.querySelectorAll('article').forEach(el => {
        const times = el.querySelectorAll('time.reply-time');
        const rt = el.querySelector('.root-time');
        const rootTime = new Date(rt.getAttribute("datetime"));
        console.log(rootTime);
        rt.title = rootTime;
        times.forEach(elem => {
            const mytime = new Date(elem.getAttribute("datetime"));
            elem.title = mytime;
            elem.innerText = `${ParseThisTimeInterval(mytime, rootTime)} 后`;
            const timeMarker = document.createElement('i');
            timeMarker.setAttribute('data-lucide', 'clock');
            timeMarker.setAttribute('width', '16px');
            timeMarker.setAttribute('height', '16px');
            timeMarker.setAttribute('class', 'time-icon');
            timeMarker.style.display = 'inline-block';
            timeMarker.style.transform = 'translateY(-2px)';
            elem.appendChild(timeMarker);
        });
    });

    let hugocounts = [];
    document.querySelectorAll(".tag").forEach(el => hugocounts.push(el.getAttribute('tag-count')));
    const countsMax = Math.max(...hugocounts);
    hugocounts = hugocounts.map(count => count / countsMax);

    const counters = document.querySelectorAll(".counter");
    counters.forEach(counter => {
        const value = counter.getAttribute("data-value");
        if (value > 5000) {
            counter.classList.add("text-red-500!");
        } else if (value > 1000) {
            counter.classList.add("text-orange-500!");
        } else if (value > 500) {
            counter.classList.add("text-yellow-500!");
        }
    });


    const nav = document.querySelector('nav.fixed');
    console.log(nav);

    if (nav) {

        let lastScrollTop = null;
        let nowTop = 0;
        let scrollDelta = 0;


        document.addEventListener("scroll", e => {

            if (!debounce) {
                window.requestAnimationFrame(function () {
                    scrollDelta = window.scrollY - lastScrollTop;
                    if (scrollDelta > 0) {
                        if (scrollDelta - nowTop > nav.clientHeight) {
                            nowTop = nav.clientHeight * -1;
                        } else {
                            nowTop = nowTop - scrollDelta;
                        }
                    }
                    else {
                        if (nowTop - scrollDelta < 0) {
                            nowTop = nowTop - scrollDelta;
                        } else {
                            nowTop = 0;
                        }
                    }
                    if (nowTop >= nav.clientHeight * -1 && nowTop <= 0) { nav.style.top = `${nowTop}px`; }
                    lastScrollTop = window.scrollY;
                });



            };
        })
    }

    createIcons({
        icons: {
            Menu,
            ArrowRight,
            Globe,
            SquareArrowOutUpRight,
            PlayingCardsFan,
            Tags,
            Clock,
            Earth,
            UsersCollaboration,
            Brush,
            BookBookmark,
            MessageCircleQuestionMark,
            Sparkles,
        }
    });
});


function thematicColorChange(event, primary) {

    let preferredTheme = event.matches;
    console.log(preferredTheme);
    document.querySelectorAll("svg.tint").forEach(el => {
        tintSVG(el, primary[preferredTheme ? 700 : 500], primary[preferredTheme ? 500 : 300]);
    });

    const svgflood = document.getElementById("svgflood");
    svgflood.setAttribute("flood-color", primary[preferredTheme ? 600 : 500]);
}

window.addEventListener("load", function () {
    const s = document.querySelectorAll(".scattered");
    console.log(s);
    s.forEach(el => {
        el.style.transform = `rotate(${Math.random() * 10 - 5}deg)`;
    });
});


function updateOverlaySize() {
    o = globalThis.borderOverlay;
    c = globalThis.container;
    o.style.top = `calc(${c.offsetTop}px - var(--border-size) / 2)`;
    o.style.left = `calc(${getComputedStyle(c).marginLeft} - var(--border-size) / 2)`;
    o.style.width = `calc(${getComputedStyle(c).width} + var(--border-size))`;
    o.style.height = `calc(${getComputedStyle(c).height} + var(--border-size))`;
}

function tintSVG(svgElement, strokeColor, fillColor){
    
    uuid = "c"+generateUID(6,'a');
    svgElement.querySelectorAll('[stroke]').forEach(el => {
        if (el.getAttribute('stroke') !== 'none') {
            el.setAttribute('stroke', strokeColor);
        }
        });

  // 修改所有有 fill 的元素
    svgElement.querySelectorAll('[fill]').forEach(el => {
        if (el.getAttribute('fill') !== 'none') {
            el.setAttribute('fill', fillColor);
        }
    });

    var c = [];
    var classes = [];

  // 也处理 style 里的颜色
    const svgStyle = svgElement.querySelector('style');
    if (svgStyle) {

        svgStyle.textContent = svgStyle.textContent
            .replace(/stroke:\s*#[0-9a-fA-F]{3,6}/g, `stroke: ${strokeColor}`)
            .replace(/fill:\s*#[0-9a-fA-F]{3,6}/g, `fill: ${fillColor}`);
            
        svgStyle.textContent.matchAll(/\.([^0-9]\S*)\s*[\,,{]/g).forEach(e => {
            c.push(e[1]);
        })
        classes = c.filter((item, index) => c.indexOf(item) === index);  // 去重
        
    }

    classes.forEach(e => {
        svgElement.innerHTML = svgElement.innerHTML.replaceAll(e, (match) => `${uuid}-${match}`);
    })

    // todo: 特定颜色不tint
}

function ParseThisTimeInterval(time, rootTime, units = { d: 'd ', h: 'h ', m: 'm ', s: 's' }) {
    var timeDiff = time - rootTime;
    var days = Math.floor(timeDiff / (1000 * 60 * 60 * 24));
    var hours = Math.floor((timeDiff % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
    var minutes = Math.floor((timeDiff % (1000 * 60 * 60)) / (1000 * 60));
    var seconds = Math.floor((timeDiff % (1000 * 60)) / 1000);

    var timeString = '';
    if (days > 0) {
        timeString += `${days}${units.d}`;
    }
    if (hours > 0) {
        timeString += `${hours}${units.h}`;
    }
    if (minutes > 0) {
        timeString += `${minutes}${units.m}`;
    }
    if (seconds > 0) {
        timeString += `${seconds}${units.s}`;
    }

    return timeString;
}


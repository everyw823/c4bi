function updateOverlaySize() {
    o = globalThis.borderOverlay;
    c = globalThis.container;
    o.style.top = `calc(${c.offsetTop}px - var(--border-size) / 2)`;
    o.style.left = `calc(${getComputedStyle(c).marginLeft} - var(--border-size) / 2)`;
    o.style.width = `calc(${getComputedStyle(c).width} + var(--border-size))`;
    o.style.height = `calc(${getComputedStyle(c).height} + var(--border-size))`;
}

function tintSVG(svgElement, strokeColor, fillColor){
    
    svgElement.querySelectorAll('[stroke]').forEach(el => {
        if (el.getAttribute('stroke') !== 'none') {
            el.setAttribute('stroke', strokeColor);
        }
        });

  // 修改所有有 fill 的元素
    svgElement.querySelectorAll('[fill]').forEach(el => {
        if (el.getAttribute('fill') !== 'none') {
            el.setAttribute('fill', fillColor);
        }
    });

  // 也处理 style 里的颜色
    const svgStyle = svgElement.querySelector('style');
    if (svgStyle) {
        svgStyle.textContent = svgStyle.textContent
            .replace(/stroke:\s*#[0-9a-fA-F]{3,6}/g, `stroke: ${strokeColor}`)
            .replace(/fill:\s*#[0-9a-fA-F]{3,6}/g, `fill: ${fillColor}`);
    }

    console.log(svgStyle);
    // todo: 特定颜色不tint
}




document.addEventListener('DOMContentLoaded', function () {
    

    
    console.log(Menu);
    const primary = {};
    const secondary = {};
    b.forEach(a => {

        primary[a] = getComputedStyle(document.documentElement).getPropertyValue(`--color-primary-${a}`).trim()
        secondary[a] = getComputedStyle(document.documentElement).getPropertyValue(`--color-secondary-${a}`).trim()

    });
    

    globalThis.borderOverlay = document.querySelector('.border-overlay');
    globalThis.container = document.getElementById('real-container');
    
    updateOverlaySize(); 

    const svgtint = document.querySelectorAll("svg.tint");
    svgtint.forEach(el => {
        tintSVG(el, primary[500], primary[300]);
    });

    svgflood = document.getElementById("svgflood");
    svgflood.setAttribute("flood-color", primary[500]);

    const links = document.querySelectorAll('a');
    const re = /\s*:\/\//;

    
    links.forEach(elem => {
        const href = elem.getAttribute("href");
        if(href && href.match(re)){
            const originalClasses = elem.getAttribute("class") ?? "";
            elem.setAttribute("class", `${originalClasses} ex`);
            elem.setAttribute("target", "_blank");
            
            // 为每个链接创建新的图标元素
            const externalMarker = document.createElement('i');
            externalMarker.setAttribute('data-lucide', 'square-arrow-out-up-right');
            externalMarker.setAttribute('width', '16px');
            externalMarker.setAttribute('height', '16px');
            externalMarker.setAttribute('class', 'external-icon');
            externalMarker.style.display = 'inline-block';
            elem.appendChild(externalMarker);
        }
    });

    createIcons({ 
        icons: { 
            Menu,
            ArrowRight,
            Globe,
            SquareArrowOutUpRight, 
            PlayingCardsFan,
        } 
    });

});

window.addEventListener('resize', function () {
    if (!debounce) {
        updateOverlaySize()

    }
    debounce = true;
    setTimeout(function () { debounce = false; }, 50);
});


